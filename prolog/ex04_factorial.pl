/* ==========================================================================
   EX.NO: 04
   TITLE: FACTORIAL OF A NUMBER
   AIM: To write a Prolog program to find the factorial of a given number.
   ========================================================================== */

% Base case: 0! = 1
fact(0, 1).

% Recursive case: N! = N * (N - 1)!
fact(N, F) :- 
    N > 0, 
    N1 is N - 1, 
    fact(N1, F1), 
    F is N * F1.

/* ==========================================================================
   SAMPLE QUERIES & EXPECTED OUTPUT:
   --------------------------------------------------------------------------
   ?- fact(5, A).
   A = 120.

   ?- fact(10, B).
   B = 3628800.

   ?- fact(5, 720).
   false.
   ========================================================================== */
